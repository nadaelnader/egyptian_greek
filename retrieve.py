bm25 = BM25Okapi(tokenized_chunks)

# ---------------------------------
# Normalize Scores
# ---------------------------------

def min_max_normalize(scores):
    scores = np.asarray(scores, dtype=float)

    if len(scores) == 0:
        return scores

    if scores.max() == scores.min():
        return np.zeros_like(scores)

    return (scores - scores.min()) / (scores.max() - scores.min())# ---------------------------------
# Hybrid Search
# ---------------------------------

ALPHA = 0.7


def hybrid_search(question, k=5):

    # =============================
    # 1. Vector Search (Chroma)
    # =============================

    query_embedding = model.encode(
        [preprocess_for_embedding(question)],
        convert_to_numpy=True,
        normalize_embeddings=True
    )


    vector_results = collection.query(
        query_embeddings=query_embedding.tolist(),
        n_results=k
    )


    vector_scores = {}

    for chunk_id, distance in zip(
        vector_results["ids"][0],
        vector_results["distances"][0]
    ):

        vector_scores[chunk_id] = 1 - distance



    # =============================
    # 2. BM25 Search
    # =============================

    bm25_query = preprocess_for_bm25(question)

    bm25_scores = bm25.get_scores(
        bm25_query.split()
    )


    bm25_scores_norm = min_max_normalize(
        bm25_scores
    )


    bm25_results = {}

    for idx, score in enumerate(bm25_scores_norm):

        bm25_results[
            chunks[idx]["chunk_id"]
        ] = score



    # =============================
    # 3. Combine Scores
    # =============================

    all_ids = set(
        list(vector_scores.keys()) +
        list(bm25_results.keys())
    )


    final_results = []


    for chunk_id in all_ids:

        vector_score = vector_scores.get(
            chunk_id,
            0
        )

        bm25_score = bm25_results.get(
            chunk_id,
            0
        )


        final_score = (
            ALPHA * vector_score
            +
            (1 - ALPHA) * bm25_score
        )


        final_results.append(
            {
                "chunk_id": chunk_id,
                "score": float(final_score)
            }
        )


    # =============================
    # 4. Sort Results
    # =============================

    final_results = sorted(
        final_results,
        key=lambda x: x["score"],
        reverse=True
    )


    # =============================
    # 5. Add Chunk Data
    # =============================

    output = []

    for result in final_results[:k]:

        for chunk in chunks:

            if chunk["chunk_id"] == result["chunk_id"]:

                item = chunk.copy()
                item["score"] = result["score"]

                output.append(item)
                break


    return output
