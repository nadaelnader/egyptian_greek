# ---------------------------------
# Detect comparison questions
# ---------------------------------
def is_comparison_question(question):

    comparison_words = [
        "compare",
        "difference",
        "different",
        "similar",
        "similarities",
        "vs",
        "versus",
    ]

    question = question.lower()

    return any(word in question for word in comparison_words)


# ---------------------------------
# Find character names mentioned in the question
# ---------------------------------
def find_characters(question):

    names = []

    question = question.lower()

    for alias, real_name in character_aliases.items():
        question = question.replace(alias, real_name)

    for doc in documents:

        title = doc["title"].lower()

        if title in question:
            names.append(doc)
            continue

        clean_title = re.sub(r"\(.*?\)", "", title).strip()

        if clean_title in question:
            names.append(doc)

    return names


# ---------------------------------
# Build Context
# ---------------------------------
def build_context(question):

    results = hybrid_search(question, k=5)

    if len(results) == 0:
        return "", []

    selected_documents = []
    seen = set()

    # ---------------------------------
    # Add mentioned characters first
    # ---------------------------------
    if is_comparison_question(question):

        mentioned = find_characters(question)

        for doc in mentioned:

            if doc["id"] not in seen:

                selected_documents.append(doc)
                seen.add(doc["id"])

    # ---------------------------------
    # Complete with Hybrid Search results
    # ---------------------------------
    for row in results:

        if row["document_id"] in seen:
            continue

        if row["score"] < 0.50:
            continue

        seen.add(row["document_id"])

        for doc in documents:

            if doc["id"] == row["document_id"]:

                selected_documents.append(doc)
                break

        if len(selected_documents) == 5:
            break

    if len(selected_documents) == 0:
        return "", []

    # ---------------------------------
    # Build Context
    # ---------------------------------
    context_parts = []

    for i, doc in enumerate(selected_documents, start=1):

        context_parts.append(
            f"==============================\n"
            f"SOURCE {i}\n"
            f"==============================\n"
            f"Title: {doc['title']}\n\n"
            f"{doc['text']}\n"
        )

    context = "\n".join(context_parts)

    return context.strip(), selected_documents

